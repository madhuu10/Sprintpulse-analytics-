@st.cache_resource
def load_attendance_artifacts():
    prep = joblib.load("model/artifacts/attendance_preprocessor.joblib")
    model = tf.keras.models.load_model("model/artifacts/attendance_model.keras")
    calibrator = joblib.load("model/artifacts/attendance_calibrator.joblib")
    bg = np.load("model/artifacts/attendance_background.npy")
    with open("model/artifacts/attendance_metrics.json") as f:
        metrics = json.load(f)
    return prep, model, calibrator, bg, metrics


@st.cache_resource
def load_sprint_artifacts():
    prep = joblib.load("model/artifacts/sprint_preprocessor.joblib")
    model = tf.keras.models.load_model("model/artifacts/sprint_model.keras")
    bg = np.load("model/artifacts/sprint_background.npy")
    with open("model/artifacts/sprint_metrics.json") as f:
        metrics = json.load(f)
    return prep, model, bg, metrics


@st.cache_resource
def get_attendance_explainer(_model, _bg, feature_names):
    def predict_fn(X):
        return _model.predict(X, verbose=0).flatten()
    return shap.Explainer(predict_fn, _bg, feature_names=feature_names)


@st.cache_resource
def get_sprint_explainer(_model, _bg, feature_names):
    def predict_fn(X):
        return _model.predict(X, verbose=0).flatten()
    return shap.Explainer(predict_fn, _bg, feature_names=feature_names)


