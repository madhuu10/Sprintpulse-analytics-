ATTEND_TIERS = attend_metrics["tier_cutoffs"]


def attendance_tier(p):
    if p < ATTEND_TIERS["low_max"]:
        return "Low", GOOD
    elif p < ATTEND_TIERS["medium_max"]:
        return "Medium", WARNING
    return "High", CRITICAL


def sprint_tier(rate):
    if rate >= 0.85:
        return "On Track", GOOD
    elif rate >= 0.60:
        return "At Risk", WARNING
    return "Off Track", CRITICAL


